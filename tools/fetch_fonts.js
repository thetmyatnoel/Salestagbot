/**
 * tools/fetch_fonts.js — downloads the web fonts the app self-hosts (nothing on the family's
 * phones may load from a third-party CDN, so the woff2 files ship inside the app bundle).
 *
 *   node tools/fetch_fonts.js            -> app/fonts/*.woff2, app/fonts/fonts.css, app/fonts/MANIFEST.json
 *
 * Source: Google Fonts' CSS endpoint, asked with a Chrome user agent so it answers with woff2 and
 * unicode-range subsets. Noto Sans Myanmar (Myanmar + Latin subsets) and IBM Plex Sans (Latin),
 * weights 400 and 600. Both are variable fonts on Google's side, so one file usually serves both
 * weights; the generated CSS then declares `font-weight: 400 600` once per subset.
 * If the download fails (no internet on the maintainer's PC), app/README.md has the manual step.
 * Node-only script: modern JS is fine here.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const https = require('https');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'app', 'fonts');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';
const FAMILIES = [
  { family: 'Noto Sans Myanmar', slug: 'NotoSansMyanmar', subsets: ['myanmar', 'latin'] },
  { family: 'IBM Plex Sans', slug: 'IBMPlexSans', subsets: ['latin', 'latin-ext'] }
];
const WEIGHTS = [400, 600];

function get(url, binary) {
  return new Promise((resolve, reject) => {
    https.get(url, { headers: { 'User-Agent': UA, Accept: binary ? '*/*' : 'text/css,*/*;q=0.1' } }, res => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        res.resume();
        return get(res.headers.location, binary).then(resolve, reject);
      }
      if (res.statusCode !== 200) { res.resume(); return reject(new Error('HTTP ' + res.statusCode + ' for ' + url)); }
      const chunks = [];
      res.on('data', c => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks)));
      res.on('error', reject);
    }).on('error', reject);
  });
}

/** Parse the @font-face blocks of a Google Fonts CSS answer into {subset, weight, url, unicodeRange}. */
function parseCss(css) {
  const out = [];
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(css)) !== null) {
    const body = m[2];
    const weight = /font-weight:\s*(\d+)/.exec(body);
    const url = /url\(([^)]+)\)/.exec(body);
    const range = /unicode-range:\s*([^;]+);/.exec(body);
    if (!weight || !url) continue;
    out.push({ subset: m[1], weight: Number(weight[1]), url: url[1].replace(/['"]/g, ''), unicodeRange: range ? range[1].trim() : '' });
  }
  return out;
}

async function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const manifest = { fetchedAt: new Date().toISOString(), source: 'https://fonts.googleapis.com/css2', files: [] };
  const cssOut = ['/* Generated by tools/fetch_fonts.js. Self-hosted: nothing here loads from a CDN. */'];
  const seen = {};
  for (const fam of FAMILIES) {
    const cssUrl = 'https://fonts.googleapis.com/css2?family=' + encodeURIComponent(fam.family).replace(/%20/g, '+') + ':wght@' + WEIGHTS.join(';') + '&display=swap';
    console.log('CSS  ' + cssUrl);
    const faces = parseCss((await get(cssUrl, false)).toString('utf8')).filter(f => fam.subsets.includes(f.subset));
    if (!faces.length) throw new Error('no @font-face blocks found for ' + fam.family);
    for (const subset of fam.subsets) {
      const bySubset = faces.filter(f => f.subset === subset);
      if (!bySubset.length) continue;
      const urls = Array.from(new Set(bySubset.map(f => f.url)));
      const sameFile = urls.length === 1;
      for (const face of bySubset) {
        if (sameFile && face !== bySubset[0]) continue;      // variable font: one file covers 400 and 600
        const bytes = seen[face.url] || (seen[face.url] = await get(face.url, true));
        const hash = crypto.createHash('sha256').update(bytes).digest('hex');
        const file = fam.slug + '-' + subset + '-' + hash.slice(0, 8) + '.woff2';
        const target = path.join(OUT, file);
        if (!fs.existsSync(target)) fs.writeFileSync(target, bytes);
        if (!manifest.files.some(f => f.file === file)) manifest.files.push({ file, family: fam.family, subset, weights: sameFile ? WEIGHTS : [face.weight], url: face.url, sha256: hash, bytes: bytes.length });
        cssOut.push('/* ' + fam.family + ' · ' + subset + ' */');
        cssOut.push('@font-face {');
        cssOut.push("  font-family: '" + fam.family + "';");
        cssOut.push('  font-style: normal;');
        cssOut.push('  font-weight: ' + (sameFile ? WEIGHTS[0] + ' ' + WEIGHTS[WEIGHTS.length - 1] : face.weight) + ';');
        cssOut.push('  font-display: swap;');
        cssOut.push("  src: url('" + file + "') format('woff2');");
        if (face.unicodeRange) cssOut.push('  unicode-range: ' + face.unicodeRange + ';');
        cssOut.push('}');
        console.log('font ' + file + ' (' + Math.round(bytes.length / 1024) + ' KB)');
      }
    }
  }
  fs.writeFileSync(path.join(OUT, 'fonts.css'), cssOut.join('\n') + '\n');
  fs.writeFileSync(path.join(OUT, 'MANIFEST.json'), JSON.stringify(manifest, null, 2) + '\n');
  console.log('wrote app/fonts/fonts.css and MANIFEST.json (' + manifest.files.length + ' files)');
}

main().catch(err => { console.error('fetch_fonts failed: ' + err.message); process.exit(1); });
